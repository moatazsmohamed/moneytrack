export const translations = { en, ar };

function language() {
  try { return getState().prefs.language === 'ar' ? 'ar' : 'en'; } catch { return 'en'; }
}

function humanize(key) {
  return String(key).split('.').pop().replace(/[_-]+/g, ' ').replace(/([a-z])([A-Z])/g, '$1 $2').replace(/^./, (char) => char.toUpperCase());
}

export function t(key, params = {}) {
  const lang = language();
  let value = translations[lang]?.[key] ?? translations.en[key] ?? humanize(key);
  if (typeof value !== 'string') return value;
  return value.replace(/\{\{?([\w.-]+)\}?\}/g, (match, name) => Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match);
}

export function number(value, digits = 0) {
  const safe = Number(value);
  if (!Number.isFinite(safe)) return '—';
  const lang = language();
  return new Intl.NumberFormat(lang === 'ar' ? 'ar-EG' : 'en-US', { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(safe);
}

export function money(value) {
  const safe = Number(value);
  if (!Number.isFinite(safe)) return '—';
  const state = getState();
  return new Intl.NumberFormat(state.prefs.language === 'ar' ? 'ar-EG' : 'en-US', {
    style: 'currency', currency: state.prefs.currency, minimumFractionDigits: 2, maximumFractionDigits: 2,
  }).format(safe);
}

export function formatDate(iso, options = {}) {
  if (typeof iso !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(iso)) return '—';
  const [year, month, day] = iso.split('-').map(Number);
  const date = new Date(year, month - 1, day);
  const defaults = { year: 'numeric', month: 'short', day: 'numeric' };
  return new Intl.DateTimeFormat(language() === 'ar' ? 'ar-EG' : 'en-US', { ...defaults, ...options }).format(date);
}

export function catName(category) {
  if (!category) return t('uncategorized');
  const lang = language();
  return category.names?.[lang] || category.names?.en || category.names?.ar || t('uncategorized');
}

export function applyLocale() {
  if (typeof document === 'undefined') return;
  const lang = language();
  const root = document.documentElement;
  root.lang = lang;
  root.dir = lang === 'ar' ? 'rtl' : 'ltr';
  root.dataset.language = lang;
  const state = getState();
  root.dataset.theme = state.prefs.theme;
  root.classList.toggle('rtl', lang === 'ar');
  root.classList.toggle('dark', state.prefs.theme === 'dark');
  if (document.body) {
    document.body.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.body.dataset.theme = state.prefs.theme;
  }
  return { language: lang, theme: state.prefs.theme, direction: root.dir };
}

